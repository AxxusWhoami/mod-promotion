-- DB: world
-- Talent templates for the mod_promotion NPC.
-- Each row is one talent (spell ID of the talent at max rank) that should be
-- learned when a player selects the <playerSpec> template.
--
-- The spec names must match the kGearSets entries in src/mod_promotion.cpp.
-- Talent IDs sourced from azerothcore/mod-npc-talent-template level 80 PvP builds.

DROP TABLE IF EXISTS `mod_promotion_talents`;
CREATE TABLE `mod_promotion_talents` (
  `playerSpec`  VARCHAR(50)  NOT NULL DEFAULT '',
  `talentId`    INT UNSIGNED  NOT NULL DEFAULT 0,
  PRIMARY KEY (`playerSpec`, `talentId`)
) ENGINE=InnoDB DEFAULT CHARSET=UTF8MB4 COMMENT='Talent templates for mod_promotion';

